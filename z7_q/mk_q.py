"""mk_q.py SRC_DIR OUT_DIR -- the _Q study set from the z7 scripts in SRC_DIR.

_Q = the same study, the same .sav and .dyr, PLUS the dynamic-data decks of the
queue projects in the vicinity: the full @input list of the DIS2301
Run1-create-snap.idv (DyreChanges, AECI, and the 24 "000_*.idv" decks). Every
other build/init step of that .idv is already what the z7 scripts do.

So a _Q run never touches a normal run, everything it writes is named apart:
    results_base_q / results_proj_q        (normal: results_base / results_proj)
    <case>_Q[...].cnl/.cnv/.snp/.sav        (normal: <case>[...])
    LOADED_*_Q_<project>.dyr                (normal: LOADED_*_<project>.dyr)
    comparison_q, comparison_scenarios_q, comparison_pairs_q
    LIVE_STATUS_Q*, SWEEP_PLAN_Q*, .spp_slots_Q_*, .spp_alive_Q_*, .spp_scoring_busy_Q
and each _Q script starts the other _Q scripts, never the normal ones.

Run again whenever the z7 scripts change: python3 mk_q.py <z7 folder> <out folder>."""
